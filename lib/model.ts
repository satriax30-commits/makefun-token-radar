// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can rank: the 40 on the watchlist (the
// floor, never a ceiling) plus every pre-token protocol below the floor that is not a product of a
// token that already trades. A protocol is pre-token when its record carries no token (no market
// cap, no CoinGecko id, no symbol). Wrapped, staked and bridged products are set aside, not ranked:
// WBTC is Bitcoin on Ethereum and a staked-ETH receipt is ETH in a staking product, so neither is a
// launch still to come. The same rule the house's watchlist uses decides it, from the snapshot's own
// fields (category, name) and never from a hand-kept list of names. Live-token protocols are kept
// apart and shown with the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.03 x min(max(chains - 1, 0), 5)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// TVL is the size of the prize, seven-day growth is its momentum, age is how long the protocol has
// run with no token (a long unlaunched record is a launch the market has waited for), and chain
// breadth is how many chains a farmer must touch. No protocol name is ever special-cased: the same
// function scores every row, and the dashboard recomputes each row from the same figures.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

